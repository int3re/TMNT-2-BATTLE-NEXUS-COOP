"""gen_postfx.py: tools/postfx.hlsl -> src/mod/postfx_shader.h (ps_3_0 bytecode as an array).

Uses D3DCompile of the system's d3dcompiler_47.dll, at development time only."""
import ctypes, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, "postfx.hlsl"), "rb").read()

dll = ctypes.WinDLL("d3dcompiler_47.dll")
D3DCompile = dll.D3DCompile
D3DCompile.restype = ctypes.c_long
D3DCompile.argtypes = [ctypes.c_char_p, ctypes.c_size_t, ctypes.c_char_p, ctypes.c_void_p, ctypes.c_void_p,
                       ctypes.c_char_p, ctypes.c_char_p, ctypes.c_uint, ctypes.c_uint,
                       ctypes.POINTER(ctypes.c_void_p), ctypes.POINTER(ctypes.c_void_p)]


def blob_bytes(blob):
    vt = ctypes.cast(ctypes.cast(blob, ctypes.POINTER(ctypes.c_void_p))[0], ctypes.POINTER(ctypes.c_void_p))
    get_ptr = ctypes.WINFUNCTYPE(ctypes.c_void_p, ctypes.c_void_p)(vt[3])
    get_size = ctypes.WINFUNCTYPE(ctypes.c_size_t, ctypes.c_void_p)(vt[4])
    return ctypes.string_at(get_ptr(blob), get_size(blob))


code, errors = ctypes.c_void_p(), ctypes.c_void_p()
O3 = 1 << 15  # D3DCOMPILE_OPTIMIZATION_LEVEL3
hr = D3DCompile(src, len(src), b"postfx.hlsl", None, None, b"main", b"ps_3_0", O3, 0, ctypes.byref(code),
                ctypes.byref(errors))
if errors:
    sys.stderr.write(blob_bytes(errors).decode("ascii", "replace"))
if hr < 0 or not code:
    sys.exit("D3DCompile failed: 0x%08X" % (hr & 0xFFFFFFFF))
data = blob_bytes(code)
assert len(data) % 4 == 0
words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
out = ["// Generated by tools/gen_postfx.py from tools/postfx.hlsl (ps_3_0). Do not edit.", "#pragma once",
       "#include <cstdint>", "", "namespace postfx {", "", "const uint32_t kShader[] = {"]
for i in range(0, len(words), 8):
    out.append("    " + ", ".join("0x%08X" % w for w in words[i:i + 8]) + ",")
out += ["};", "", "}  // namespace postfx", ""]
path = os.path.join(HERE, "..", "src", "mod", "postfx_shader.h")
open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("ps_3_0: %d bytes -> %s" % (len(data), os.path.normpath(path)))
